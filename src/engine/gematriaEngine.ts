export function calculateGematria(text: string, cipher: Cipher) {
  let val = 0;
  let textNorm = text.normalize('NFD').replace(/[\u0300-\u036f]/g, "").toLowerCase();
  
  let chars = Array.from(textNorm);
  let breakdown: {char: string, val: number|string}[] = [];
  
  for (let c of chars) {
    let cp = c.codePointAt(0);
    if (cp === undefined) continue;
    let idx = cipher.cArr.indexOf(cp);
    if (idx > -1) {
      let v = cipher.vArr[idx];
      val += typeof v === 'number' ? v : 0;
      breakdown.push({char: c, val: v});
    } else if (c.trim() !== "") {
      breakdown.push({char: c, val: 0});
    }
  }
  return { value: val, breakdown };
}

export interface GematriaPremiumResult {
  letters: string[];
  ordinal: { char: string; val: number }[];
  reduced: { char: string; val: number }[];
  ordValue: number;
  redValue: number;
  ordReduced: number;
  redReduced: number;
}

export function calculateGematriaPremium(text: string): GematriaPremiumResult {
  const letters = text.toUpperCase().normalize('NFD').replace(/[\u0300-\u036f]/g, "").replace(/[^A-Z]/g, '');
  const ordinal: { char: string; val: number }[] = [];
  const reduced: { char: string; val: number }[] = [];
  let ordSum = 0;
  let redSum = 0;

  for (let char of letters) {
    const val = char.charCodeAt(0) - 64;
    ordinal.push({ char, val });
    
    let redVal = val;
    if (val === 11) {
      redVal = 11; // K stays 11
    } else if (val === 22) {
      redVal = 22; // V stays 22
    } else {
      let sum = val.toString().split('').reduce((acc, d) => acc + parseInt(d, 10), 0);
      if (sum === 2) {
        redVal = 11; // No-2 rule
      } else {
        redVal = sum;
      }
    }
    
    reduced.push({ char, val: redVal });
    ordSum += val;
    redSum += redVal;
  }

  const reduceFinalVal = (num: number): number => {
    const MASTER_NUMS = [11, 22, 33];
    if (MASTER_NUMS.includes(num)) return num;
    let n = num;
    while (n > 9) {
      n = n.toString().split('').reduce((acc, d) => acc + parseInt(d, 10), 0);
    }
    return n;
  };

  return {
    letters: letters.split(''),
    ordinal,
    reduced,
    ordValue: ordSum,
    redValue: redSum,
    ordReduced: reduceFinalVal(ordSum),
    redReduced: reduceFinalVal(redSum)
  };
}
